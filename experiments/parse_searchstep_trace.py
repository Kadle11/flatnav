        if not output_file:
            output_file = os.path.join(
                output_dir,
                f"{trace.dataset_name}_trace_dump_q{max_queries_label}.json",
            )

        os.makedirs(os.path.dirname(output_file) or output_dir, exist_ok=True)

        with open(output_file, "w", encoding="utf-8") as handle:
            json.dump(output_data, handle, indent=2)

        logging.info(f"Saved trace JSON dump to {output_file}")


