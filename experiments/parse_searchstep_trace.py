def _strip_trace_args(raw_args: List[str]) -> List[str]:
    """Return argv tokens without --trace-file/--trace-files arguments."""
    filtered_args: List[str] = []
    index = 0

    while index < len(raw_args):
        token = raw_args[index]

        if token == "--trace-file":
            index += 2
            continue

        if token.startswith("--trace-file="):
            index += 1
            continue

        if token == "--trace-files":
            index += 1
            while index < len(raw_args) and not raw_args[index].startswith("--"):
                index += 1
            continue

        if token.startswith("--trace-files="):
            index += 1
            continue

        filtered_args.append(token)
        index += 1

    return filtered_args


def main():
    """Main entry point."""
    # Parse arguments first to handle --list-plugins
    args = parse_args()
    
    # Set logging level
    if args.verbose:
        logging.getLogger().setLevel(logging.DEBUG)
    
    # Handle --list-plugins
    if args.list_plugins:
        print("\nAvailable Analysis Plugins:")
        print("=" * 80)
        for name, plugin in PLUGIN_REGISTRY.plugins.items():
            print(f"\n{name}:")
            print(f"  {plugin.description}")
        print("\n")
        return
    
    trace_files: List[str] = []
    if args.trace_files:
        trace_files.extend(args.trace_files)
    if args.trace_file:
        trace_files.append(args.trace_file)

    # Check that at least one trace file is provided
    if not trace_files:
        logging.error("Provide --trace-file or --trace-files when not using --list-plugins")
        return

    # If multiple trace files are provided, launch one subprocess per trace file
    if len(trace_files) > 1:
        script_path = os.path.abspath(__file__)
        forwarded_args = _strip_trace_args(sys.argv[1:])
        base_cmd = [sys.executable, script_path, *forwarded_args]

        logging.info(f"Launching {len(trace_files)} subprocesses (one per trace file)")
        processes: List[Tuple[str, subprocess.Popen]] = []

        for trace_file in trace_files:
            cmd = [*base_cmd, "--trace-file", trace_file]
            logging.info(f"Starting subprocess: {' '.join(shlex.quote(part) for part in cmd)}")
            process = subprocess.Popen(cmd)
            processes.append((trace_file, process))

        failed_traces: List[str] = []
        for trace_file, process in processes:
            return_code = process.wait()
            if return_code != 0:
                failed_traces.append(trace_file)
                logging.error(f"Subprocess failed for {trace_file} with exit code {return_code}")

        if failed_traces:
            logging.error(
                f"Completed with failures for {len(failed_traces)} trace file(s): {', '.join(failed_traces)}"
            )
            sys.exit(1)

        logging.info("All subprocesses completed successfully")
        return
    
    # Load trace
    trace, dataset_name = load_trace(trace_files[0])
    
    # Create output directory
    output_dir = args.output_dir
    os.makedirs(output_dir, exist_ok=True)
    logging.info(f"Output directory: {output_dir}")
    
    # Check if any plugins are enabled
    if not args.plugins:
        logging.warning("No plugins enabled. Use --plugins to specify plugins to run.")
        logging.info(f"Available plugins: {', '.join(PLUGIN_REGISTRY.list_plugins())}")
        return
    
    # Run enabled plugins
    print("\n" + "=" * 80)
    print(f"Running Analysis for: {dataset_name}")
    print("=" * 80)
    
    for plugin_name in args.plugins:
        plugin = PLUGIN_REGISTRY.get(plugin_name)
        
        if plugin is None:
            logging.error(f"Unknown plugin: {plugin_name}")
            logging.info(f"Available plugins: {', '.join(PLUGIN_REGISTRY.list_plugins())}")
            continue
        
        print(f"\n--- Running Plugin: {plugin.name} ---")
        try:
            plugin.analyze(trace, args, output_dir)
            print(f"✓ Plugin '{plugin.name}' completed successfully")
        except Exception as e:
            logging.error(f"Plugin '{plugin.name}' failed with error: {e}", exc_info=True)
            print(f"✗ Plugin '{plugin.name}' failed")
    
    print("\n" + "=" * 80)
    print(f"Analysis complete! Results saved to: {output_dir}")
    print("=" * 80 + "\n")


if __name__ == "__main__":
    main()
