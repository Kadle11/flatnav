def load_trace(trace_file: str) -> Tuple[SearchStepTrace, str]:
    """
    Load search step trace from pickle file.
    
    Returns:
        Tuple of (SearchStepTrace, dataset_name)
    """
    if not os.path.exists(trace_file):
        raise FileNotFoundError(f"Trace file not found: {trace_file}")
    
    # Extract dataset name from filename (e.g., gist-960-euclidean_searchstep_trace.pkl)
    filename = os.path.basename(trace_file)
    dataset_name = filename.replace("_searchstep_trace.pkl", "")
    
    logging.info(f"Loading trace file: {trace_file}")
    
    with open(trace_file, 'rb') as f:
        trace_data = pickle.load(f)
    
    trace = SearchStepTrace(trace_data, dataset_name)
    
    return trace, dataset_name


