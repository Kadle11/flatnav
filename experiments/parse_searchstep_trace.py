class PhaseOverlapPerQueryPlugin(AnalysisPlugin):
    """Analyze phase-based overlap of explored and candidate nodes per individual query."""
    
    @property
    def name(self) -> str:
        return "phase_overlap_per_query"
    
    @property
    def description(self) -> str:
        return "Analyze overlap of nodes/accesses between consecutive search phases per query"
    
    def analyze(self, trace: SearchStepTrace, args: argparse.Namespace, output_dir: str):
        phase_size = args.phase_size

        logging.info(f"Computing per-query phase overlap with phase_size={phase_size}")

        all_nodes = ("all", None)
        hub_nodes = ("hubs", lambda node_id: trace.is_hub(node_id))
        non_hub_nodes = ("non_hubs", lambda node_id: not trace.is_hub(node_id))

        for label, predicate in (all_nodes, hub_nodes, non_hub_nodes):
            phase_aggregates = self._collect_phase_aggregates(trace, phase_size, predicate)
            if not phase_aggregates:
                logging.warning(f"No phase aggregates to plot for {label}")
                continue

            self._plot_phase_overlap(
                phase_aggregates,
                trace.dataset_name,
                phase_size,
                output_dir,
                title_suffix=label,
                output_suffix=label,
            )

    def _collect_phase_aggregates(
        self,
        trace: SearchStepTrace,
        phase_size: int,
        predicate: Optional[callable],
    ) -> List[Dict[str, float]]:
        all_query_metrics = []
        skipped_queries = 0

        for query in trace.queries:
            query_id = query["query_id"]
            search_steps = query["search_steps"]

            if len(search_steps) < phase_size * 2:
                skipped_queries += 1
                continue

            num_phases = len(search_steps) // phase_size
            if num_phases < 2:
                skipped_queries += 1
                continue

            logging.debug(f"Query {query_id}: {len(search_steps)} steps, {num_phases} phases")
            phase_metrics = []

            for phase_idx in range(1, num_phases):
                prev_phase_start = (phase_idx - 1) * phase_size
                prev_phase_end = phase_idx * phase_size
                curr_phase_start = phase_idx * phase_size
                curr_phase_end = (phase_idx + 1) * phase_size

                prev_steps = search_steps[prev_phase_start:prev_phase_end]
                curr_steps = search_steps[curr_phase_start:curr_phase_end]

                prev_explored_nodes = set()
                prev_candidate_nodes = set()
                curr_explored_nodes = set()
                curr_candidate_nodes = set()

                prev_explored_accesses = []
                prev_candidate_accesses = []
                curr_explored_accesses = []
                curr_candidate_accesses = []

                for step in prev_steps:
                    for node_id in step["explored_list"]:
                        if predicate is None or predicate(node_id):
                            prev_explored_nodes.add(node_id)
                            prev_explored_accesses.append(node_id)
                    for node_id in step["candidate_list"]:
                        if predicate is None or predicate(node_id):
                            prev_candidate_nodes.add(node_id)
                            prev_candidate_accesses.append(node_id)

                for step in curr_steps:
                    for node_id in step["explored_list"]:
                        if predicate is None or predicate(node_id):
                            curr_explored_nodes.add(node_id)
                            curr_explored_accesses.append(node_id)
                    for node_id in step["candidate_list"]:
                        if predicate is None or predicate(node_id):
                            curr_candidate_nodes.add(node_id)
                            curr_candidate_accesses.append(node_id)

                explored_node_overlap = len(curr_explored_nodes & prev_explored_nodes)
                candidate_node_overlap = len(curr_candidate_nodes & prev_candidate_nodes)

                explored_node_overlap_pct = (explored_node_overlap / len(curr_explored_nodes) * 100) if curr_explored_nodes else 0
                candidate_node_overlap_pct = (candidate_node_overlap / len(curr_candidate_nodes) * 100) if curr_candidate_nodes else 0

                prev_explored_set = set(prev_explored_accesses)
                prev_candidate_set = set(prev_candidate_accesses)

                explored_access_overlap = sum(1 for node in curr_explored_accesses if node in prev_explored_set)
                candidate_access_overlap = sum(1 for node in curr_candidate_accesses if node in prev_candidate_set)

                explored_access_overlap_pct = (explored_access_overlap / len(curr_explored_accesses) * 100) if curr_explored_accesses else 0
                candidate_access_overlap_pct = (candidate_access_overlap / len(curr_candidate_accesses) * 100) if curr_candidate_accesses else 0

                if query_id == 0 and phase_idx == 1:
                    logging.info("Query 0, Phase 1 overlap percentages:")
                    logging.info(f"  Explored nodes: {explored_node_overlap_pct:.2f}%")
                    logging.info(f"  Candidate nodes: {candidate_node_overlap_pct:.2f}%")
                    logging.info(f"  Explored accesses: {explored_access_overlap_pct:.2f}%")
                    logging.info(f"  Candidate accesses: {candidate_access_overlap_pct:.2f}%")

                phase_metrics.append({
                    "phase_idx": phase_idx,
                    "explored_node_overlap_pct": explored_node_overlap_pct,
                    "candidate_node_overlap_pct": candidate_node_overlap_pct,
                    "explored_access_overlap_pct": explored_access_overlap_pct,
                    "candidate_access_overlap_pct": candidate_access_overlap_pct,
                })

            if phase_metrics:
                all_query_metrics.append(phase_metrics)

        logging.info(f"Processed {len(all_query_metrics)} queries with sufficient phases, skipped {skipped_queries} queries")

        if not all_query_metrics:
            logging.warning(f"No queries with sufficient phases (need at least {phase_size * 2} steps)")
            logging.info(f"Total queries in trace: {len(trace.queries)}")
            if trace.queries:
                sample_query = trace.queries[0]
                logging.info(f"Sample query has {len(sample_query['search_steps'])} steps")
            return []

        max_phases = max(len(metrics) for metrics in all_query_metrics)

        phase_aggregates = []
        for phase_idx in range(max_phases):
            explored_node_vals = []
            traversed_node_vals = []
            explored_access_vals = []
            traversed_access_vals = []

            for query_metrics in all_query_metrics:
                if phase_idx < len(query_metrics):
                    m = query_metrics[phase_idx]
                    explored_node_vals.append(m["explored_node_overlap_pct"])
                    candidate_node_vals.append(m["candidate_node_overlap_pct"])
                    explored_access_vals.append(m["explored_access_overlap_pct"])
                    candidate_access_vals.append(m["candidate_access_overlap_pct"])

            phase_aggregates.append({
                "phase_idx": phase_idx + 1,
                "explored_node_mean": np.mean(explored_node_vals),
                "explored_node_std": np.std(explored_node_vals),
                "candidate_node_mean": np.mean(candidate_node_vals),
                "candidate_node_std": np.std(candidate_node_vals),
                "explored_access_mean": np.mean(explored_access_vals),
                "explored_access_std": np.std(explored_access_vals),
                "candidate_access_mean": np.mean(candidate_access_vals),
                "candidate_access_std": np.std(candidate_access_vals),
            })

        logging.info(f"Phase overlap analysis complete. Analyzed {len(all_query_metrics)} queries with {max_phases} phases.")

        if phase_aggregates:
            logging.info(f"Sample phase aggregate (phase 1): {phase_aggregates[0]}")
            logging.debug(f"All phase aggregates: {phase_aggregates}")

        return phase_aggregates
    
    def _plot_phase_overlap(
        self,
        phase_aggregates: List[Dict[str, float]],
        dataset_name: str,
        phase_size: int,
        output_dir: str,
        title_suffix: str,
        output_suffix: str,
    ):
        """Create bar plot of phase overlap percentages."""
        
        if not phase_aggregates:
            logging.warning("No phase aggregates to plot")
            return
        
        logging.info(f"Plotting {len(phase_aggregates)} phases")
        
        fig, ax = plt.subplots(figsize=(14, 8))
        
        phase_indices = np.array([p["phase_idx"] for p in phase_aggregates])
        
        explored_node_means = np.array([p["explored_node_mean"] for p in phase_aggregates])
        explored_node_stds = np.array([p["explored_node_std"] for p in phase_aggregates])
        
        candidate_node_means = np.array([p["candidate_node_mean"] for p in phase_aggregates])
        candidate_node_stds = np.array([p["candidate_node_std"] for p in phase_aggregates])
        
        explored_access_means = np.array([p["explored_access_mean"] for p in phase_aggregates])
        explored_access_stds = np.array([p["explored_access_std"] for p in phase_aggregates])
        
        candidate_access_means = np.array([p["candidate_access_mean"] for p in phase_aggregates])
        candidate_access_stds = np.array([p["candidate_access_std"] for p in phase_aggregates])
        
        logging.debug(f"Explored node means: {explored_node_means}")
        logging.debug(f"Candidate node means: {candidate_node_means}")
        logging.debug(f"Explored access means: {explored_access_means}")
        logging.debug(f"Candidate access means: {candidate_access_means}")
        
        # Bar width and positions
        bar_width = 0.2
        x = np.arange(len(phase_indices))
        
        # Create bars
        bars1 = ax.bar(x - 1.5*bar_width, explored_node_means, bar_width, 
                       yerr=explored_node_stds, capsize=3, label='Explored Nodes',
                       color='#3498db', alpha=0.8)
        
        bars2 = ax.bar(x - 0.5*bar_width, candidate_node_means, bar_width,
                       yerr=candidate_node_stds, capsize=3, label='Candidate Nodes',
                       color='#e74c3c', alpha=0.8)
        
        bars3 = ax.bar(x + 0.5*bar_width, explored_access_means, bar_width,
                       yerr=explored_access_stds, capsize=3, label='Explored Accesses',
                       color='#2ecc71', alpha=0.8)
        
        bars4 = ax.bar(x + 1.5*bar_width, candidate_access_means, bar_width,
                       yerr=candidate_access_stds, capsize=3, label='Candidate Accesses',
                       color='#f39c12', alpha=0.8)
        
        # Add value labels on top of bars
        def add_value_labels(bars, values):
            for bar, value in zip(bars, values):
                height = bar.get_height()
                ax.text(bar.get_x() + bar.get_width()/2., height + 1,
                       f'{value:.1f}%',
                       ha='center', va='bottom', rotation=45, fontsize=8)
        
        add_value_labels(bars1, explored_node_means)
        add_value_labels(bars2, candidate_node_means)
        add_value_labels(bars3, explored_access_means)
        add_value_labels(bars4, candidate_access_means)
        
        # Formatting
        ax.set_xlabel('Phase Number', fontsize=12, fontweight='bold')
        ax.set_ylabel('Overlap Percentage (%)', fontsize=12, fontweight='bold')
        ax.set_title(f'Phase-to-Phase Overlap Analysis ({title_suffix})\n{dataset_name} (Phase Size: {phase_size})',
                    fontsize=14, fontweight='bold')
        ax.set_xticks(x)
        ax.set_xticklabels(phase_indices)
        ax.legend(loc='upper right', fontsize=10)
        ax.grid(axis='y', alpha=0.3, linestyle='--')
        ax.set_ylim(0, max(110, max(explored_node_means.max(), candidate_node_means.max(),
                                     explored_access_means.max(), candidate_access_means.max()) + 10))
        
        plt.tight_layout()
        
        # Save plot
        output_file = os.path.join(output_dir, f"{dataset_name}_phase_overlap_per_query_{output_suffix}_phase{phase_size}.png")
        plt.savefig(output_file, dpi=300, bbox_inches='tight')
        logging.info(f"Saved phase overlap plot to {output_file}")
        plt.close()


