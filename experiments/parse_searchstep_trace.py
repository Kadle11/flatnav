        print(f"  num_queries_processed: {trace.trace_params.get('num_queries_processed', len(trace.queries))}")

        print(f"\nDegree Statistics (Nodes in is_hub structure):")
        print(f"  Node degree entries: {stats['node_degrees_count']}")
        print(f"  All nodes - In-degree: avg={stats['all_in_degree_avg']:.2f}, median={stats['all_in_degree_median']:.2f}, top90={stats['all_in_degree_top_90']:.2f}, top99={stats['all_in_degree_top_99']:.2f}")
