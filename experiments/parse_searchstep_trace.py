class SummaryStatsPlugin(AnalysisPlugin):
    """Print summary statistics about the trace."""
    
    @property
    def name(self) -> str:
        return "summary"
    
    @property
    def description(self) -> str:
        return "Print summary statistics about the trace"
    
    def analyze(self, trace: SearchStepTrace, args: argparse.Namespace, output_dir: str):
        stats = trace.get_query_stats()
        
        print("\n" + "=" * 80)
        print(f"TRACE SUMMARY: {trace.dataset_name}")
        print("=" * 80)
        print(f"Dataset: {trace.dataset_name}")
        print(f"Hub percentile: {trace.hub_percentile}")

        print(f"\nTrace Generation Parameters:")
        print(f"  k: {trace.trace_params.get('k', 'N/A')}")
        print(f"  ef_construction: {trace.trace_params.get('ef_construction', 'N/A')}")
        print(f"  ef_search: {trace.trace_params.get('ef_search', 'N/A')}")
        print(f"  num_node_links: {trace.trace_params.get('num_node_links', 'N/A')}")
        print(f"  hub_percentile: {trace.trace_params.get('hub_percentile', trace.hub_percentile)}")
