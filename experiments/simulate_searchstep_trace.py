        print(f"  Avg candidates per step: {summary['avg_candidates_per_step']:.2f}")
        print()
        print("Data movement totals:")
        print(f"  Adjacency request bytes: {summary['bytes']['total_adjacency_request_bytes']}")
        print(f"  Adjacency response bytes: {summary['bytes']['total_adjacency_response_bytes']}")
        print(f"  Compute request bytes: {summary['bytes']['total_compute_request_bytes']}")
        print(f"  Compute response bytes: {summary['bytes']['total_compute_response_bytes']}")
        print(f"  Adjacency bytes: {summary['bytes']['total_adjacency_bytes']}")
        print(f"  Vector fetch bytes: {summary['bytes']['total_vector_fetch_bytes']}")
        print()
        print("Runtime totals:")
        print(f"  Total runtime: {summary['runtime_ns']:.2f} ns")
        print(f"             = {summary['runtime_us']:.2f} us")
        print(f"             = {summary['runtime_ms']:.2f} ms")
